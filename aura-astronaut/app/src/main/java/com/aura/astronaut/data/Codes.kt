package com.aura.astronaut.data

/*
 * v5 contract codes (English) the app stores and sends. The equivalences with v4 are in
 * contract/v4-to-v5.md; the local database migration 3→4 translates what was already stored.
 */

/** Review of an adaptation by mission control (`review.status`). */
object ReviewStatus {
    const val PENDING = "pending"
    const val VALIDATED = "validated"
    const val OBJECTED = "objected"
}

/** Acknowledgement of an alert by mission control (`ack.status`). */
object AckStatus {
    const val NEW = "new"
    const val SEEN = "seen"
    const val HANDLED = "handled"
}

/** Kind and level of an alert (`kind`, `level`). */
object AlertCodes {
    const val KIND_RED = "capacity-red"
    const val KIND_PREP = "preparation-lost"
    const val KIND_CONSISTENCY = "inconsistency"
    const val LEVEL_RED = "red"
    const val LEVEL_WARNING = "warning"
}

/** `source` of adaptations and alerts generated by the interface. */
const val SOURCE_INTERFACE = "interface"
