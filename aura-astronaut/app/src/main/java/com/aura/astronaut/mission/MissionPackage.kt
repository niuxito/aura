// ---------- Self-assessment (v4): capacities, signals and daily questionnaire ----------
// Defined by mission control; the interface applies them. All thresholds are for demonstration.

/** State of a capacity. GRAY = insufficient data; green is never shown by default. */
@Serializable
enum class CapacityLevel {
    @SerialName("green") GREEN,
    @SerialName("amber") AMBER,
    @SerialName("red") RED,
    @SerialName("gray") GRAY,
}

@Serializable
data class Capacity(
    val id: String,
    val name: LocalizedText,
    val description: LocalizedText,
    /** What the interface does in amber, always within adaptationPolicy. */
    val onAmber: LocalizedText,
    /** What the interface does in red: refers and alerts; does not decide on its own. */
    val onRed: LocalizedText,
    /** Concrete substitutions the interface applies in amber (for example, the hydration menu). */
    val onAmberActions: List<AmberAction> = emptyList(),
    /**
     * Arrival environments in which this capacity is critical for leaving the spacecraft.
     * null = the package does not declare it (older packages).
     */
    val criticalFor: List<Gravity>? = null,
)

/** In amber, today's adaptable activity of [category] becomes [replacementItemId]. */
@Serializable
data class AmberAction(val category: Category, val replacementItemId: String)

@Serializable
enum class SignalSource {
    @SerialName("watch") WATCH,
    @SerialName("garment") GARMENT,
    @SerialName("test") TEST,
}

@Serializable
enum class SignalKind {
    @SerialName("number") NUMBER,
    @SerialName("boolean") BOOLEAN,
}

/** In which direction a numeric signal gets worse. */
@Serializable
enum class WorseWhen {
    @SerialName("higher") HIGHER,
    @SerialName("lower") LOWER,
}

@Serializable
enum class ComparisonOp {
    @SerialName(">=") AT_LEAST,
    @SerialName("<=") AT_MOST,
}

@Serializable
data class Signal(
    val id: String,
    val name: LocalizedText,
    val unit: String,
    val source: SignalSource,
    /** true = no real device in the demo: the interface generates values flagged as simulated. */
    val simulated: Boolean,
    val capacityId: String,
    val kind: SignalKind,
    /** Numeric only. */
    val worseWhen: WorseWhen? = null,
    /** Numeric only: from which value (inclusive) it turns amber or red; null = n/a. */
    val amber: Double? = null,
    val red: Double? = null,
    /** Boolean only: level when the signal is true. */
    val whenTrue: CapacityLevel? = null,
    val description: LocalizedText,
)

@Serializable
data class QuestionScale(val min: Int, val max: Int)

@Serializable
data class QuestionVariant(
    val id: String,
    val text: LocalizedText,
    val minLabel: LocalizedText,
    val maxLabel: LocalizedText,
    /** true = phrased positively (high = better): normalized with (max + min) − value so that high = worse. */
    val inverted: Boolean,
)

@Serializable
enum class QuestionBlock {
    /** Block A: every day. */
    @SerialName("fixed") FIXED,
    /** Block B: according to triggers. */
    @SerialName("bank") BANK,
}

/** When a bank question enters the day's questionnaire (`kind` field in the JSON). */
@OptIn(ExperimentalSerializationApi::class)
@Serializable
@JsonClassDiscriminator("kind")
sealed interface QuestionTrigger {
    val priority: Int
    val reason: LocalizedText

    /** Flight days before or after one with a gravity transition. */
    @Serializable
    @SerialName("transition")
    data class Transition(
        override val priority: Int,
        override val reason: LocalizedText,
        val daysBefore: Int,
        val daysAfter: Int,
        /** Only transitions into these environments; empty = any. */
        val toGravity: List<Gravity> = emptyList(),
        val minDaysInMicro: Int? = null,
    ) : QuestionTrigger

    @Serializable
    @SerialName("environment")
    data class Environment(
        override val priority: Int,
        override val reason: LocalizedText,
        val gravity: List<Gravity>,
    ) : QuestionTrigger

    @Serializable
    @SerialName("micro-days")
    data class DaysInMicro(
        override val priority: Int,
        override val reason: LocalizedText,
        val min: Int,
    ) : QuestionTrigger

    @Serializable
    @SerialName("event")
    data class Event(
        override val priority: Int,
        override val reason: LocalizedText,
        val eventKind: EventKind,
        val withinDays: Int,
    ) : QuestionTrigger

    /** For boolean signals it fires when true; [op] and [value] are ignored. */
    @Serializable
    @SerialName("signal")
    data class SignalValue(
        override val priority: Int,
        override val reason: LocalizedText,
        val signalId: String,
        val op: ComparisonOp? = null,
        val value: Double? = null,
    ) : QuestionTrigger

    /** Filler when there are not enough triggered questions. */
    @Serializable
    @SerialName("filler")
    data class Filler(
        override val priority: Int,
        override val reason: LocalizedText,
    ) : QuestionTrigger
}

@Serializable
data class QuestionItem(
    val id: String,
    val block: QuestionBlock,
    val domain: LocalizedText,
    val capacityId: String,
    val scale: QuestionScale,
    /** Instrument it is inspired by; a single question is not the validated instrument. */
    val inspiredBy: LocalizedText,
    val variants: List<QuestionVariant>,
    /** On the normalized value (high = worse), inclusive; null = n/a. */
    val amber: Double? = null,
    val red: Double? = null,
    val triggers: List<QuestionTrigger>,
)

/** Consistency between self-report and sensor: detects under-reporting. */
@Serializable
data class ConsistencyCheck(
    val id: String,
    val questionId: String,
    /** Normalized answer at or below this = the astronaut says they are fine. */
    val answerAtMost: Double,
    val signalId: String,
    val op: ComparisonOp,
    val value: Double,
    val message: LocalizedText,
)

@Serializable
data class Questionnaire(
    /** Catalog action that schedules it in the plan. */
    val catalogItemId: String,
    val name: LocalizedText,
    val source: LocalizedText,
    val fixedPerDay: Int,
    val bankPerDay: Int,
    val items: List<QuestionItem>,
    val consistencyChecks: List<ConsistencyCheck>,
)

/** Value of [AdaptationType] as it travels in the JSON. */
val AdaptationType.wire: String
    get() = when (this) {
        AdaptationType.SUBSTITUTION -> "substitution"
        AdaptationType.RESCHEDULE -> "reschedule"
        AdaptationType.OMISSION -> "omission"
    }
