    @SerialName("moon") MOON,
    @SerialName("mars") MARS,
}

@Serializable
enum class LoadLevel {
    @SerialName("low") LOW,
    @SerialName("medium") MEDIUM,
    @SerialName("high") HIGH,
    @SerialName("critical") CRITICAL,
}

@Serializable
enum class Category {
