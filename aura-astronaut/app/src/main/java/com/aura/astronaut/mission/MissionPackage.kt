package com.aura.astronaut.mission

import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonClassDiscriminator

/*
 * Models of the mission package `aura.mission-package/v5` (English codes and LocalizedText texts).
 * Source of truth: ../aura-manager/lib/package.ts and ../aura-manager/lib/types.ts.
 * If they change there, update these models and contract/mission-package.example.json.
 * Every MET is in seconds (Long); the *Label fields are for display only.
 */

/** Manager schema. v3 and v4 packages are no longer accepted (contract/v4-to-v5.md). */
const val SUPPORTED_SCHEMA = "aura.mission-package/v5"

@Serializable
data class MissionPackage(
    val schema: String,
    val packageVersion: Int,
    val publishedAt: String,
    /** Languages the texts come in, and the fallback one. */
    val languages: List<String> = listOf("en"),
    val defaultLanguage: String = "en",
    /** `sha256:<hex>` of the package's canonical JSON without this field. */
    val checksum: String? = null,
    /** true if the mission or the prevention plan is an example, not a prescription. */
    val simulated: Boolean,
    val mission: Mission,
    val gravityReference: Map<Gravity, Double>,
    val crew: List<CrewMember>,
    val days: List<FlightDay>,
    val events: List<MissionEvent>,
    val blocks: List<TimelineBlock>,
    val catalog: List<CatalogItem>,
    val adaptationPolicy: AdaptationPolicy,
    /** crewId → one element per flight day, with activities sorted by MET. */
    val plans: Map<String, List<DayPlan>>,
    /** Traffic-light capacities in the interface and what to do in amber or red. */
    val capacities: List<Capacity>,
    /** Objective signals; simulated ones are generated by the interface and labeled as such. */
    val signals: List<Signal>,
    /** Daily questionnaire: fixed block, triggered bank and thresholds. */
    val questionnaire: Questionnaire,
    /** Every threshold in capacities, signals and questionnaire is for demonstration. */
    val thresholdsAreDemo: Boolean = true,
    val validation: List<ValidationIssue>,
)

@Serializable
data class Mission(
    val id: String,
    val name: LocalizedText,
    val destination: LocalizedText,
    val description: LocalizedText,
    /** UTC instant of MET 0 (launch), or null if not set. */
    val launchUtc: String? = null,
    val timelineSource: String,
    val simulated: Boolean,
)

@Serializable
data class CrewMember(
    val id: String,
    val name: String,
    val role: LocalizedText,
    /** Baseline resting HR (bpm). Demonstration value; null = unknown. */
    val restingHrBpm: Int? = null,
)

@Serializable
data class FlightDay(
    val day: Int,
    val label: String,
    val startMet: Long,
    val endMet: Long,
    val startMetLabel: String,
    val endMetLabel: String,
    val phase: LocalizedText,
    val milestone: LocalizedText,
    /** Gravity environment at the end of the flight day. */
    val gravity: Gravity,
    /** Only if there is a gravity transition that day: departure environment. */
    val transitionFrom: Gravity? = null,
    /** Exact MET of the transition (launch, splashdown), if the package carries it. */
    val transitionMet: Long? = null,
    /** Estimated operational load. */
    val opLoad: LoadLevel,
)

@Serializable
data class MissionEvent(
    val id: String,
    val met: Long,
    val metLabel: String,
    val day: Int? = null,
    val name: LocalizedText,
    val kind: EventKind,
    /** The timeline gives it as approximate: shown with "~". */
    val approx: Boolean,
)

@Serializable
data class TimelineBlock(
    val id: String,
    val startMet: Long,
    val endMet: Long,
    val startMetLabel: String,
    val endMetLabel: String,
    val name: LocalizedText,
    val kind: BlockKind,
    /** true = period whose content the interface may adapt. */
    val adaptable: Boolean,
    val adaptableCategories: List<Category>,
)

@Serializable
data class CatalogItem(
    val id: String,
    val code: String,
    val name: LocalizedText,
    val category: Category,
    val loadType: LoadType,
    val intense: Boolean,
    val transitionPrep: Boolean,
    val selfReport: Boolean,
    val capabilities: List<LocalizedText>,
    /** What the monitor must record. */
    val record: LocalizedText,
    /** Limit of use or interpretation: it must be shown. */
    val limit: LocalizedText,
    /** null = no prescribed dose. The interface never invents or changes doses. */
    val dose: LocalizedText? = null,
    val source: LocalizedText,
    val sourceUrl: String? = null,
    val experimental: Boolean = false,
    /** Planned duration in minutes (team estimate); null = unknown. */
    val durationMin: Int? = null,
)

@Serializable
data class AdaptationPolicy(
    /** Adaptable category → block kind within which it may move. */
    val windows: Map<Category, BlockKind>,
    val allowed: List<AdaptationType>,
    val rules: List<LocalizedText>,
    val report: ReportPolicy,
)

@Serializable
data class ReportPolicy(val endpoint: String, val method: String, val blocking: Boolean)

@Serializable
data class DayPlan(val day: Int, val activities: List<PlanActivity>)

@Serializable
data class PlanActivity(
    /** Stable reference cited by adaptations. */
    val entryId: String,
    /** Points to [CatalogItem.id]. */
    val itemId: String,
    val met: Long,
    val metLabel: String,
    val status: EntryStatus,
    /** true = the interface may adapt it according to [AdaptationPolicy]. */
    val adaptable: Boolean,
    /** Planned end (catalog duration); null if the package does not carry it. */
    val endMet: Long? = null,
    val note: LocalizedText? = null,
)

@Serializable
data class ValidationIssue(
    val id: String,
    val rule: String,
    val severity: Severity,
    /** Flight day; null = the whole mission. */
    val day: Int? = null,
    val crewId: String? = null,
    val message: LocalizedText,
)

